clc;
clear all;
close all;
N=input('Enter the length of sequence:');
x=input('Enter the value of signal sequence of length N;');
n1=input('Enter the amount to be delayed:');
n2=input('Enter the amou8nt to be advanced:');
n=0:N-1;
subplot(3,1,1);
stem(n,x);
title('Signal x(n)');
xlabel('n');
ylabel('Amplitude');
grid on;
m=n+n1;
y=x;
subplot(3,1,2);
stem(m,y);
title('Delayed Signal x(n-n1)');
xlabel('n');
ylabel('Amplitude');
grid on;
z=x;
subplot(3,1,3);
stem(t,z);
title('Advanced Signal x(n+n2)');
xlabel('n');
ylabel('Amplitude');
grid on;
